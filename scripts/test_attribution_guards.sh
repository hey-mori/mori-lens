test_clean_pr_body() {
  local body="## Summary
- Add feature X
- Fix bug Y

## Testing
- All tests pass"

  local matches
  matches="$(printf '%s' "$body" | grep -oEi 'Co-Authored-By|Generated with|Generated by AI|AI-assisted|Claude Code|Qwen|🤖' || true)"

  if [ -z "$matches" ]; then
    ok "clean PR body passes"
  else
    die "clean PR body should not match forbidden patterns: $matches"
  fi
}

test_bad_pr_body() {
  local body="## Summary
- Add feature X

Generated with Claude Code
🤖 Generated with [Claude Code](https://claude.com)"

  local matches
  matches="$(printf '%s' "$body" | grep -oEi 'Co-Authored-By|Generated with|Generated by AI|AI-assisted|Claude Code|Qwen|🤖' | sort -u || true)"

  if [ -n "$matches" ]; then
    ok "PR body with forbidden attribution is detected"
  else
    die "PR body with forbidden attribution should be detected"
  fi
}

