#!/usr/bin/env bash
#
# Behavioral regression tests for attribution enforcement hooks.
#
# Creates isolated temporary git repositories to test:
#   - commit-msg hook rejects forbidden attribution before commit object creation
#   - pre-push hook rejects new commits with forbidden attribution
#   - pre-push hook allows clean commits even when historical commits have violations
#   - PR body checker rejects forbidden attribution
#
# Minimum fixtures (per user requirement):
#   1. clean new branch commit → push gate PASS
#   2. new branch commit with Co-Authored-By → FAIL
#   3. new branch commit with Generated with → FAIL
#   4. existing branch에 clean follow-up → PASS
#   5. existing branch에 bad follow-up → FAIL
#   6. historical bad commit + clean new follow-up → PASS
#   7. direct main push → FAIL
#   8. non-fast-forward → FAIL
#   9. PR body clean → PASS
#  10. PR body with forbidden attribution → FAIL
#
# Run from the repository root:
#   bash scripts/test_attribution_guards.sh
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PRE_PUSH_HOOK="$REPO_ROOT/.githooks/pre-push"

PASS=0
FAIL=0

cleanup() {
  rm -rf "$TMPDIR"
}

die() {
  echo "  FAIL: $*"
  FAIL=$((FAIL + 1))
}

ok() {
  echo "  PASS: $*"
  PASS=$((PASS + 1))
}

TMPDIR="$(mktemp -d)"
trap cleanup EXIT

echo "Testing attribution enforcement hooks..."
echo ""

# ============================================================
# commit-msg hook tests
# ============================================================

echo "=== commit-msg hook tests ==="

# Test 1: clean commit message passes
test_clean_commit() {
  local testdir="$TMPDIR/test1"
  mkdir -p "$testdir"
  git init -q "$testdir"
  git -C "$testdir" config user.email "test@test"
  git -C "$testdir" config user.name "Test"
  git -C "$testdir" config core.hooksPath "$REPO_ROOT/.githooks"

  echo "test" > "$testdir/file.txt"
  git -C "$testdir" add file.txt

  cat > "$testdir/msg.txt" <<'EOF'
feat: add a clean feature

- Add clean feature with proper format
- No forbidden attribution
EOF

  local output
  output="$(git -C "$testdir" commit -F "$testdir/msg.txt" 2>&1)" && true
  if [ $? -eq 0 ] || echo "$output" | grep -q "created"; then
    ok "clean commit message passes commit-msg hook"
  else
    die "clean commit message should pass commit-msg hook"
  fi
}

