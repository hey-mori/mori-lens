ZERO="0000000000000000000000000000000000000000"

# Test 4: clean new branch commit passes push gate
test_clean_new_branch() {
  local testdir="$TMPDIR/test4"
  mkdir -p "$testdir"
  git init -q "$testdir"
  git -C "$testdir" config user.email "test@test"
  git -C "$testdir" config user.name "Test"

  echo "a" > "$testdir/a.txt"
  git -C "$testdir" add a.txt
  git -C "$testdir" commit -q --no-verify -m "feat: initial commit

- Initial commit"

  git -C "$testdir" checkout -q -b feature
  echo "b" > "$testdir/b.txt"
  git -C "$testdir" add b.txt
  git -C "$testdir" commit -q --no-verify -m "feat: add feature

- Add feature"
  local feature_sha
  feature_sha="$(git -C "$testdir" rev-parse HEAD)"

  local input="refs/heads/feature $feature_sha refs/heads/feature $ZERO"
  local output
  output="$(printf '%s\n' "$input" | GIT_DIR="$testdir/.git" bash "$PRE_PUSH_HOOK" origin http://example 2>&1)" || true
  local rc=$?

  # Check if hook exited with 0 (success)
  if [ -z "$(echo "$output" | grep -E 'ERROR|rejected|forbidden|violates')" ]; then
    ok "clean new branch commit passes push gate"
  else
    die "clean new branch commit should pass push gate: $output"
  fi
}

