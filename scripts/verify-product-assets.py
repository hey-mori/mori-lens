def compute_file_hash(filepath):
    """Compute SHA-256 hash of a file."""
    sha256 = hashlib.sha256()
    with open(filepath, "rb") as f:
        for chunk in iter(lambda: f.read(8192), b""):
            sha256.update(chunk)
    return sha256.hexdigest()


def verify_png_dimensions(filepath, expected_width, expected_height):
    """Verify PNG file has expected dimensions."""
    try:
        with Image.open(filepath) as img:
            width, height = img.size
            if width != expected_width or height != expected_height:
                return False, f"dimensions {width}x{height} != expected {expected_width}x{expected_height}"
            return True, f"dimensions {width}x{height} OK"
    except Exception as e:
        return False, f"failed to read PNG: {e}"


def verify_ico_format(filepath):
    """Verify ICO file format."""
    try:
        with open(filepath, "rb") as f:
            data = f.read(6)
            if len(data) < 6:
                return False, "file too short"
            # ICO format: reserved (2 bytes) + type (2 bytes) + count (2 bytes)
            reserved, img_type, count = int.from_bytes(data[0:2], "little"), int.from_bytes(data[2:4], "little"), int.from_bytes(data[4:6], "little")
            if reserved != 0:
                return False, f"reserved field {reserved} != 0"
            if img_type != 1:
                return False, f"type {img_type} != 1 (ICO)"
            if count < 1:
                return False, "no images in ICO"
            return True, f"ICO format OK, {count} images"
    except Exception as e:
        return False, f"failed to read ICO: {e}"


def verify_icns_format(filepath):
    """Verify ICNS file format."""
    try:
        with open(filepath, "rb") as f:
            magic = f.read(4)
            if magic != b"icns":
                return False, f"magic {magic!r} != 'icns'"
            return True, "ICNS format OK"
    except Exception as e:
        return False, f"failed to read ICNS: {e}"


def main():
    print("=" * 70)
    print("Production Asset Verification")
    print("=" * 70)

    errors = []
    warnings = []

    # Step 1: Verify each production asset
    print("\n1. Verifying production assets...")
    for asset_path, spec in PRODUCTION_ASSETS.items():
        full_path = REPO_ROOT / asset_path
        print(f"\n   Checking {asset_path}...")

        # Check file exists
        if not full_path.exists():
            errors.append(f"{asset_path}: file not found")
            print(f"      ERROR: file not found")
            continue

        # Check format/dimensions
        asset_type = spec["type"]
        if asset_type == "png":
            ok, msg = verify_png_dimensions(full_path, spec["width"], spec["height"])
            if not ok:
                errors.append(f"{asset_path}: {msg}")
                print(f"      ERROR: {msg}")
            else:
                print(f"      OK: {msg}")
        elif asset_type == "ico":
            ok, msg = verify_ico_format(full_path)
            if not ok:
                errors.append(f"{asset_path}: {msg}")
                print(f"      ERROR: {msg}")
            else:
                print(f"      OK: {msg}")
        elif asset_type == "icns":
            ok, msg = verify_icns_format(full_path)
            if not ok:
                errors.append(f"{asset_path}: {msg}")
                print(f"      ERROR: {msg}")
            else:
                print(f"      OK: {msg}")

        # Check not a smoke placeholder
        prod_hash = compute_file_hash(full_path)
        smoke_hash = SMOKE_ASSET_HASHES.get(asset_path)
        if smoke_hash and prod_hash == smoke_hash:
            errors.append(f"{asset_path}: matches smoke placeholder (hash collision)")
            print(f"      ERROR: matches smoke placeholder")
        else:
            print(f"      OK: not a smoke placeholder")

    # Summary
    print("\n" + "=" * 70)
    if errors:
        print(f"FAILED: {len(errors)} error(s)")
        for err in errors:
            print(f"  - {err}")
        sys.exit(1)
    else:
        print("PASSED: all production assets verified")
        print(f"  - {len(PRODUCTION_ASSETS)} assets checked")
        print(f"  - all formats valid")
        print(f"  - no smoke placeholders detected")
        sys.exit(0)


if __name__ == "__main__":
    main()
