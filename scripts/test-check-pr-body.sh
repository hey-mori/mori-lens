#!/usr/bin/env bash
#
# Regression tests for scripts/check-pr-body.sh
#
# This script tests the PR body checker's pattern matching logic
# against known-good and known-bad inputs.
#
# Usage:
#   scripts/test-check-pr-body.sh
#
# Exit codes:
#   0 - All tests pass
#   1 - One or more tests failed
set -euo pipefail

cd "$(dirname "$0")/.."

passed=0
failed=0

# The forbidden patterns from check-pr-body.sh (excluding emoji which is checked separately)
patterns='Co-Authored-By|Generated with|Generated by AI|AI-assisted|AI assisted|Claude Code|Qwen'

# Helper to test if a body matches forbidden patterns
# Usage: test_body "description" "body_content" should_match (0=no, 1=yes)
test_body() {
  local desc="$1"
  local body="$2"
  local should_match="$3"

  printf 'Testing: %s... ' "$desc"

  # Check for robot emoji separately (UTF-8 multi-byte handling)
  local has_emoji=0
  if printf '%s' "$body" | LC_ALL=C grep -q '🤖'; then
    has_emoji=1
  fi

  # Check text patterns
  local matches
  matches="$(printf '%s' "$body" | grep -oEi "$patterns" | sort -u)" || true

  local did_match=0
  if [[ -n "$matches" ]] || [[ $has_emoji -eq 1 ]]; then
    did_match=1
  fi

  if [[ $did_match -eq $should_match ]]; then
    printf 'PASS\n'
    passed=$((passed + 1))
  else
    if [[ $should_match -eq 1 ]]; then
      printf 'FAIL (should have matched but did not)\n'
    else
      printf 'FAIL (should not have matched but did: %s)\n' "$matches"
    fi
    failed=$((failed + 1))
  fi
}

printf 'Running PR body checker regression tests...\n\n'

# Test 1: Clean body should not match
test_body "clean body (no attribution)" \
  "## Summary
- Fixed bug
- Added tests

## Test plan
- [x] Tests pass" \
  0

# Test 2: "Generated with Claude Code" should match
test_body "Generated with Claude Code" \
  "## Summary
- Fixed bug

🤖 Generated with [Claude Code](https://claude.com/claude-code)" \
  1

# Test 3: Robot emoji only should match
test_body "robot emoji only" \
  "## Summary
- Fixed bug

🤖" \
  1

# Test 4: Qwen attribution should match
test_body "Qwen attribution" \
  "## Summary
- Fixed bug

Generated with Qwen" \
  1

# Test 5: Co-Authored-By should match
test_body "Co-Authored-By" \
  "## Summary
- Fixed bug

Co-Authored-By: Claude <noreply@anthropic.com>" \
  1

# Test 6: "AI-assisted" should match
test_body "AI-assisted" \
  "## Summary
- Fixed bug (AI-assisted)" \
  1

# Test 7: "AI assisted" (no hyphen) should match
test_body "AI assisted (no hyphen)" \
  "## Summary
- Fixed bug (AI assisted)" \
  1

# Test 8: "Generated by AI" should match
test_body "Generated by AI" \
  "## Summary
- Fixed bug

Generated by AI" \
  1

# Test 9: Ordinary word "Claude" in technical context should NOT match
# (The policy forbids "Claude Code" as a product attribution, not the word "Claude" itself)
test_body "ordinary word 'Claude' in technical context" \
  "## Summary
- Updated Claude model documentation
- Discussed Claude API integration" \
  0

# Test 10: Empty body should not match
test_body "empty body" \
  "" \
  0

# Test 11: Case insensitivity - "claude code" lowercase should match
test_body "case insensitive: 'claude code'" \
  "## Summary
- Fixed bug

claude code" \
  1

# Test 12: Case insensitivity - "CO-AUTHORED-BY" uppercase should match
test_body "case insensitive: 'CO-AUTHORED-BY'" \
  "## Summary
- Fixed bug

CO-AUTHORED-BY: Test" \
  1

# Test 13: "generated WITH" mixed case should match
test_body "case insensitive: 'generated WITH'" \
  "## Summary
- Fixed bug

generated WITH Claude" \
  1

# Summary
printf '\n'
if [[ $failed -eq 0 ]]; then
  printf '✓ All %d tests passed\n' "$passed"
  exit 0
else
  printf '✗ %d of %d tests failed\n' "$failed" "$((passed + failed))"
  exit 1
fi
