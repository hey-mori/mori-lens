#!/usr/bin/env bash
#
# Single source of truth for commit message validation.
#
# Usage:
#   scripts/validate-commit-message.sh <message-file>
#   echo "$message" | scripts/validate-commit-message.sh --stdin
#
# Exit 0 if the message passes docs/commit-format.md, exit 1 with
# diagnostics on stderr otherwise.
#
# Called by:
#   - .githooks/commit-msg (before commit creation)
#   - .githooks/pre-push (before push)
#   - scripts/check-commit-policy.sh (CI gate)
set -euo pipefail

# Read message from file or stdin
if [ "${1:-}" = "--stdin" ]; then
  msg="$(cat)"
elif [ -n "${1:-}" ] && [ -f "$1" ]; then
  msg="$(cat "$1")"
else
  echo "Usage: $0 <message-file> | $0 --stdin" >&2
  exit 2
fi

subject="$(echo "$msg" | head -1)"
errors=""

valid_types="feat|fix|perf|refactor|test|docs|chore"

# 1. Subject must start with a valid type prefix.
if ! echo "$subject" | grep -qE "^(${valid_types}): .+"; then
  errors="${errors}ERROR: subject must start with '<type>: ' where type is one of: ${valid_types}\n"
fi

# 2. Subject must be under 72 characters.
if [ "${#subject}" -gt 72 ]; then
  errors="${errors}ERROR: subject is ${#subject} chars (max 72)\n"
fi

# 3. No trailing period on subject.
if echo "$subject" | grep -q '\.$'; then
  errors="${errors}ERROR: subject must not end with a period\n"
fi

# 4. No Co-Authored-By lines.
if echo "$msg" | grep -qi 'co-authored-by:'; then
  errors="${errors}ERROR: Co-Authored-By is forbidden (docs/commit-format.md)\n"
fi

# 5. No "Generated with" or "Generated by" lines.
if echo "$msg" | grep -qiE 'generated (with|by)'; then
  errors="${errors}ERROR: 'Generated with/by' lines are forbidden\n"
fi

# 6. No "AI-assisted" or "AI assisted" lines.
if echo "$msg" | grep -qiE 'ai[- ]assisted'; then
  errors="${errors}ERROR: 'AI-assisted' lines are forbidden\n"
fi

# 7. No AI product attribution.
if echo "$msg" | grep -qiE '(claude|qwen|copilot|chatgpt|gemini) (code|sonnet|opus|haiku|ai|assistant)'; then
  errors="${errors}ERROR: AI product attribution is forbidden (docs/commit-format.md)\n"
fi

# 8. No emoji in commit messages.
if echo "$msg" | grep -qP '[\x{1F300}-\x{1F9FF}]' 2>/dev/null; then
  errors="${errors}ERROR: emoji in commit messages is forbidden\n"
fi

# 9. Body must be bullet-only (every non-blank line after subject starts with "- ").
body="$(echo "$msg" | tail -n +3)"
if [ -n "$body" ]; then
  while IFS= read -r line; do
    [ -z "$line" ] && continue
    if ! echo "$line" | grep -q '^- '; then
      errors="${errors}ERROR: body line does not start with '- ': $(echo "$line" | head -c 60)\n"
      break
    fi
  done <<< "$body"
fi

if [ -n "$errors" ]; then
  echo -e "$errors" >&2
  exit 1
fi

exit 0
