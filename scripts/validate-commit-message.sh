#!/usr/bin/env bash
#
# Single source of truth for commit message validation.
#
# Usage:
#   scripts/validate-commit-message.sh <message-file>
#   echo "$message" | scripts/validate-commit-message.sh --stdin
#
# Exit 0 if the message passes docs/commit-format.md, exit 1 with
# diagnostics on stderr otherwise.
#
# Called by:
#   - .githooks/commit-msg (before commit creation)
#   - .githooks/pre-push (before push)
#   - scripts/check-commit-policy.sh (CI gate)
set -euo pipefail

# Read message from file or stdin
if [ "${1:-}" = "--stdin" ]; then
  msg="$(cat)"
elif [ -n "${1:-}" ] && [ -f "$1" ]; then
  msg="$(cat "$1")"
else
  echo "Usage: $0 <message-file> | $0 --stdin" >&2
  exit 2
fi

subject="$(echo "$msg" | head -1)"
errors=""

valid_types="feat|fix|perf|refactor|test|docs|chore"

# Merge commits keep the message git or GitHub writes (docs/git-workflow.md:
# merge commits, never squash), including a pull request title as the body,
# which is not a bullet. Bringing main into a branch is a merge too, since
# rewriting a pushed branch is refused. Those subjects skip the shape rules
# (1-3, 9-10) and are still checked for attribution (4-8).
is_merge=""
if echo "$subject" | grep -qE "^Merge (pull request #[0-9]+ from |branch '|remote-tracking branch '|[0-9a-f]{7,40} into )"; then
  is_merge=1
fi

if [ -z "$is_merge" ]; then
  # 1. Subject must start with a valid type prefix.
  if ! echo "$subject" | grep -qE "^(${valid_types}): .+"; then
    errors="${errors}ERROR: subject must start with '<type>: ' where type is one of: ${valid_types}\n"
  fi

  # 2. Subject must be under 72 characters.
  if [ "${#subject}" -gt 72 ]; then
    errors="${errors}ERROR: subject is ${#subject} chars (max 72)\n"
  fi

  # 3. No trailing period on subject.
  if echo "$subject" | grep -q '\.$'; then
    errors="${errors}ERROR: subject must not end with a period\n"
  fi
fi

# 4. No Co-Authored-By lines.
if echo "$msg" | grep -qi 'co-authored-by:'; then
  errors="${errors}ERROR: Co-Authored-By is forbidden (docs/commit-format.md)\n"
fi

# 5. No "Generated with" or "Generated by" lines.
if echo "$msg" | grep -qiE 'generated (with|by)'; then
  errors="${errors}ERROR: 'Generated with/by' lines are forbidden\n"
fi

# 6. No "AI-assisted" or "AI assisted" lines.
if echo "$msg" | grep -qiE 'ai[- ]assisted'; then
  errors="${errors}ERROR: 'AI-assisted' lines are forbidden\n"
fi

# 7. No AI product attribution.
if echo "$msg" | grep -qiE '(claude|qwen|copilot|chatgpt|gemini) (code|sonnet|opus|haiku|ai|assistant)'; then
  errors="${errors}ERROR: AI product attribution is forbidden (docs/commit-format.md)\n"
fi

# 8. No emoji in commit messages.
# Matched as UTF-8 bytes under the C locale, so the rule holds under any locale
# and any grep. grep -P needs a UTF-8 locale and the BSD grep on macOS has no
# -P; either way the old pattern errored and the rule skipped itself silently.
# F0 9F 8C-AB is U+1F300 to U+1FAFF, E2 98-9E is U+2600 to U+27BF.
if printf '%s' "$msg" | LC_ALL=C grep -qE $'\xf0\x9f[\x8c-\xab]|\xe2[\x98-\x9e]'; then
  errors="${errors}ERROR: emoji in commit messages is forbidden\n"
fi

# 9. Body must be bullet-only (every non-blank line after subject starts with "- ").
body="$(echo "$msg" | tail -n +3)"
if [ -n "$body" ] && [ -z "$is_merge" ]; then
  while IFS= read -r line; do
    [ -z "$line" ] && continue
    if ! echo "$line" | grep -q '^- '; then
      errors="${errors}ERROR: body line does not start with '- ': $(echo "$line" | head -c 60)\n"
      break
    fi
  done <<< "$body"

  # 10. Bullets are consecutive: no blank line between them.
  #
  # Rule 9 skips blank lines, so it accepts a body whose bullets are separated by
  # them. That is how 17 commits in this repository came to have it, against 748
  # that do not: the convention was already unanimous and simply unenforced.
  #
  # The body is one list. A blank line between bullets makes `git log` read as
  # paragraphs, which is the prose shape the bullet rule exists to prevent, and
  # renders as several separate lists rather than one wherever Markdown is
  # applied to a commit body.
  seen_bullet=""
  blank_since_bullet=""
  while IFS= read -r line; do
    if echo "$line" | grep -q '^- '; then
      if [ -n "$seen_bullet" ] && [ -n "$blank_since_bullet" ]; then
        errors="${errors}ERROR: blank line between bullets; the body is one list\n"
        break
      fi
      seen_bullet=1
      blank_since_bullet=""
    elif [ -z "$line" ] && [ -n "$seen_bullet" ]; then
      blank_since_bullet=1
    fi
  done <<< "$body"
fi

if [ -n "$errors" ]; then
  echo -e "$errors" >&2
  exit 1
fi

exit 0
