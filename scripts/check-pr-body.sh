#!/usr/bin/env bash
#
# Scan a GitHub PR body for forbidden AI-attribution tokens.
#
# The project's commit format (docs/commit-format.md) forbids
# Co-Authored-By, "Generated with", and similar markers. PR bodies
# are merge-committed into main, so the same rule applies here.
#
# Usage:
#   scripts/check-pr-body.sh <pr-number>
#
# Exits 0 when the body is clean, 1 when any forbidden token is found.
# Does not modify the PR.
set -euo pipefail

cd "$(dirname "$0")/.."

if [[ $# -ne 1 ]]; then
  printf 'usage: %s <pr-number>\n' "$(basename "$0")"
  exit 2
fi

pr="$1"

body="$(gh pr view "$pr" --json body --jq '.body' 2>&1)" || {
  printf 'error: could not fetch PR #%s body\n' "$pr"
  printf '%s\n' "$body"
  exit 2
}

if [[ -z "$body" || "$body" == "null" ]]; then
  printf 'PR #%s body is empty\n' "$pr"
  exit 0
fi

# Forbidden patterns (case-insensitive):
#   Co-Authored-By
#   Generated with
#   Generated by AI
#   AI-assisted
#   Claude Code
#   Qwen
#   robot emoji
patterns='Co-Authored-By|Generated with|Generated by AI|AI-assisted|AI assisted|Claude Code|Qwen|🤖'

matches="$(printf '%s' "$body" | grep -oEi "$patterns" | sort -u)" || true

if [[ -n "$matches" ]]; then
  printf 'PR #%s body contains forbidden attribution tokens:\n' "$pr"
  while IFS= read -r match; do
    printf '  - %s\n' "$match"
  done <<< "$matches"
  exit 1
fi

printf 'PR #%s body is clean\n' "$pr"
